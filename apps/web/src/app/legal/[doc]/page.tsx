export function generateStaticParams() {
  return Object.keys(DOCS).map((doc) => ({ doc }));
}

export default async function LegalPage({ params }: { params: Promise<{ doc: string }> }) {
  const { doc } = await params;
  const d = DOCS[doc];
  if (!d) notFound();
  return (
    <div className="mx-auto max-w-2xl px-5 py-10">
      <Link href="/">
        <Logo />
      </Link>
      <h1 className="mt-10 text-3xl font-semibold text-white">{d.title}</h1>
      <div className="mt-8 space-y-6">
        {d.sections.map(([h, p]) => (
          <section key={h}>
            <h2 className="font-semibold text-white">{h}</h2>
            <p className="mt-1.5 leading-relaxed text-fog-300">{p}</p>
          </section>
        ))}
      </div>
    </div>
  );
}
