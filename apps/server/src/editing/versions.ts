/*
 * Shot versions: every generation and every AI edit of a shot is an immutable version. The movie
 * uses one active version per shot; switching never deletes media and never touches other shots.
 */

export type ShotVersion = typeof shotVersions.$inferSelect;

export async function ownedProject(ctx: AppContext, user: SessionLike, projectId: string) {
  const [p] = await ctx.db.select().from(projects).where(eq(projects.id, projectId));
  if (!p || (p.userId !== user.id && user.role !== 'admin')) throw notFound('Project');
  return p;
}

export async function ownedShot(ctx: AppContext, user: SessionLike, shotId: string) {
  const [s] = await ctx.db.select().from(shots).where(eq(shots.id, shotId));
  if (!s) throw notFound('Shot');
  const project = await ownedProject(ctx, user, s.projectId);
  return { shot: s, project };
}

/** Add a version (numbered per shot). `activate` makes it the shot's current media in the same transaction. */
export async function recordShotVersion(
  db: Db,
  p: { projectId: string; shotId: string; assetId: string; source: 'generated' | 'ai_edit' | 'upload'; label: string; parentVersionId?: string | null; operationId?: string; prompt?: string | null; settings?: Record<string, unknown>; activate: boolean },
): Promise<ShotVersion> {
  return db.transaction(async (tx) => {
    const t = tx as unknown as Db;
    await t.execute(sql`select id from ${shots} where ${shots.id} = ${p.shotId} for update`);
    const [last] = await t.select({ n: shotVersions.number }).from(shotVersions).where(eq(shotVersions.shotId, p.shotId)).orderBy(desc(shotVersions.number)).limit(1);
    const [v] = await t
      .insert(shotVersions)
      .values({ projectId: p.projectId, shotId: p.shotId, number: (last?.n ?? 0) + 1, assetId: p.assetId, source: p.source, label: p.label, parentVersionId: p.parentVersionId ?? null, operationId: p.operationId, prompt: p.prompt ?? null, settings: p.settings ?? {} })
      .returning();
    if (p.activate) await t.update(shots).set({ currentAssetId: p.assetId, activeVersionId: v!.id, status: 'ready', updatedAt: new Date() }).where(eq(shots.id, p.shotId));
    return v!;
  });
}

/**
 * Make sure every generated shot has its versions recorded (projects made before versions existed,
 * or a shot regenerated by the movie pipeline since the last look).
 */
export async function syncShotVersions(ctx: AppContext, projectId: string): Promise<void> {
  const rows = await ctx.db.select().from(shots).where(eq(shots.projectId, projectId));
  if (!rows.length) return;
  const versions = await ctx.db.select().from(shotVersions).where(eq(shotVersions.projectId, projectId));
  for (const s of rows) {
    if (!s.currentAssetId) continue;
    const mine = versions.filter((v) => v.shotId === s.id);
    const active = mine.find((v) => v.id === s.activeVersionId);
    if (active?.assetId === s.currentAssetId) continue;
    const existing = mine.find((v) => v.assetId === s.currentAssetId);
    if (existing) {
      await ctx.db.update(shots).set({ activeVersionId: existing.id }).where(eq(shots.id, s.id));
      continue;
    }
    await recordShotVersion(ctx.db, { projectId, shotId: s.id, assetId: s.currentAssetId, source: 'generated', label: mine.length ? 'Regenerated' : 'Original', parentVersionId: active?.id ?? null, prompt: s.prompt, activate: true });
  }
}

/** Every shot of the project with its versions, comments and AI edit operations (for the editor). */
export async function projectShots(ctx: AppContext, user: SessionLike, projectId: string) {
  const project = await ownedProject(ctx, user, projectId);
  await syncShotVersions(ctx, projectId);
  const sceneRows = await ctx.db.select().from(scenes).where(eq(scenes.projectId, projectId)).orderBy(asc(scenes.index));
  const shotRows = await ctx.db.select().from(shots).where(eq(shots.projectId, projectId));
  const versions = await ctx.db.select().from(shotVersions).where(eq(shotVersions.projectId, projectId)).orderBy(asc(shotVersions.number));
  const ops = await ctx.db.select().from(editOperations).where(eq(editOperations.projectId, projectId)).orderBy(asc(editOperations.createdAt));
  const comments = await ctx.db.select().from(shotComments).where(eq(shotComments.projectId, projectId)).orderBy(asc(shotComments.createdAt));
  // The cast: this project's characters and any saved character a shot uses (Character Bible).
  const castIds = [...new Set(shotRows.flatMap((s) => s.characterIds))];
  const castRows = await ctx.db
    .select()
    .from(characters)
    .where(and(eq(characters.userId, project.userId), castIds.length ? or(eq(characters.projectId, projectId), inArray(characters.id, castIds)) : eq(characters.projectId, projectId)));
  const castRefs = castRows.length ? await ctx.db.select().from(characterReferences).where(inArray(characterReferences.characterId, castRows.map((c) => c.id))) : [];
  const placeRows = await ctx.db.select({ id: locations.id, name: locations.name }).from(locations).where(eq(locations.projectId, projectId));
  const assetIds = [...new Set([...versions.map((v) => v.assetId), ...shotRows.flatMap((s) => (s.storyboardAssetId ? [s.storyboardAssetId] : [])), ...castRefs.map((r) => r.assetId)])];
  const assetRows = assetIds.length ? await ctx.db.select().from(assets).where(inArray(assets.id, assetIds)) : [];
  const thumbIds = assetRows.flatMap((a) => (a.thumbnailAssetId ? [a.thumbnailAssetId] : []));
  const thumbRows = thumbIds.length ? await ctx.db.select().from(assets).where(inArray(assets.id, thumbIds)) : [];
  const media = new Map<string, { url: string; thumbnailUrl: string | null; durationSec: number | null; isFixture: boolean }>();
  for (const a of assetRows) {
    const th = thumbRows.find((t) => t.id === a.thumbnailAssetId);
    media.set(a.id, { url: await assetUrl(ctx, a), thumbnailUrl: th ? await assetUrl(ctx, th) : a.mediaType === 'image' ? await assetUrl(ctx, a) : null, durationSec: a.durationMs ? a.durationMs / 1000 : null, isFixture: a.isFixture });
  }
  const sceneIndex = new Map(sceneRows.map((s, i) => [s.id, i]));
  const ordered = [...shotRows].sort((a, b) => (sceneIndex.get(a.sceneId)! - sceneIndex.get(b.sceneId)!) || a.index - b.index);
  const settings = project.settings as { brief?: { style?: string }; graph?: { removed?: string[] } };
  return {
    kind: project.kind,
    style: settings.brief?.style ?? null,
    /** Generated shots the user took out of the movie (they are not put back automatically). */
    removed: settings.graph?.removed ?? [],
    scenes: sceneRows.map((s) => ({ id: s.id, index: s.index, title: s.title, synopsis: s.synopsis, place: placeRows.find((l) => l.id === s.locationId)?.name ?? null })),
    characters: castRows.map((c) => {
      const ref = castRefs.filter((r) => r.characterId === c.id).sort((a, b) => Number(b.isPrimary) - Number(a.isPrimary))[0];
      return { id: c.id, name: c.name, description: c.description, clothing: c.clothing, appearance: c.appearance, voice: c.voice, styleMeta: c.styleMeta, imageUrl: ref ? (media.get(ref.assetId)?.url ?? null) : null, inProject: c.projectId === projectId };
    }),
    shots: ordered.map((s, i) => ({
      id: s.id,
      number: i + 1,
      index: s.index,
      sceneId: s.sceneId,
      description: s.description,
      prompt: s.prompt,
      camera: s.camera,
      shotType: s.shotType,
      durationSec: s.durationSec,
      status: s.status,
      approved: s.approved,
      characterIds: s.characterIds,
      dialogue: s.dialogue,
      sfx: s.sfx,
      continuityFlags: s.continuityFlags,
      activeVersionId: s.activeVersionId,
      storyboardUrl: s.storyboardAssetId ? (media.get(s.storyboardAssetId)?.url ?? null) : null,
      storyboardIsFixture: s.storyboardAssetId ? (media.get(s.storyboardAssetId)?.isFixture ?? false) : false,
      versions: versions.filter((v) => v.shotId === s.id).map((v) => ({ ...v, media: media.get(v.assetId) ?? null })),
      operations: ops.filter((o) => o.shotId === s.id),
      comments: comments.filter((c) => c.shotId === s.id),
    })),
  };
}

/**
 * Use a version in the movie: the shot points at it and every timeline clip of that shot follows
 * (trims kept when they fit). Other shots and all other versions stay exactly as they were.
 */
export async function activateShotVersion(ctx: AppContext, user: SessionLike, versionId: string) {
  const [v] = await ctx.db.select().from(shotVersions).where(eq(shotVersions.id, versionId));
  if (!v) throw notFound('Version');
  const { shot } = await ownedShot(ctx, user, v.shotId);
  const [asset] = await ctx.db.select().from(assets).where(eq(assets.id, v.assetId));
  if (!asset) throw badRequest('This version’s media is missing');
  const [prevAsset] = shot.currentAssetId ? await ctx.db.select().from(assets).where(eq(assets.id, shot.currentAssetId)) : [];
  const durationSec = (asset.durationMs ?? 5000) / 1000;
  const previousDurationSec = prevAsset?.durationMs ? prevAsset.durationMs / 1000 : undefined;
  await ctx.db.transaction(async (tx) => {
    const t = tx as unknown as Db;
    await t.update(shots).set({ currentAssetId: v.assetId, activeVersionId: v.id, status: 'ready', updatedAt: new Date() }).where(eq(shots.id, shot.id));
    const [latest] = await t.select().from(projectVersions).where(eq(projectVersions.projectId, shot.projectId)).orderBy(desc(projectVersions.version)).limit(1).for('update');
    if (latest) {
      const next = swapShotVersion(timelineSchema.parse(latest.timeline), shot.id, { assetId: v.assetId, versionId: v.id, durationSec, previousDurationSec });
      await t.insert(projectVersions).values({ projectId: shot.projectId, version: latest.version + 1, timeline: next, label: `Shot version V${v.number}`, createdBy: user.id });
    }
  });
  return { shotId: shot.id, versionId: v.id, assetId: v.assetId, durationSec, previousDurationSec };
}

export async function renameShotVersion(ctx: AppContext, user: SessionLike, versionId: string, label: string) {
  const [v] = await ctx.db.select().from(shotVersions).where(eq(shotVersions.id, versionId));
  if (!v) throw notFound('Version');
  await ownedShot(ctx, user, v.shotId);
  await ctx.db.update(shotVersions).set({ label: label.slice(0, 80) }).where(eq(shotVersions.id, versionId));
}

/** Story-graph layout (node positions, collapsed scenes) — presentation only, stored on the project. */
/** Save the story graph's layout; only the parts given change (positions, collapsed scenes, shots out of the movie). */
export async function saveGraphLayout(ctx: AppContext, user: SessionLike, projectId: string, layout: { positions?: Record<string, { x: number; y: number }>; collapsed?: string[]; removed?: string[] }) {
  const p = await ownedProject(ctx, user, projectId);
  const prev = (p.settings as { graph?: Record<string, unknown> }).graph ?? {};
  const next = Object.fromEntries(Object.entries(layout).filter(([, v]) => v !== undefined));
  await ctx.db.update(projects).set({ settings: { ...(p.settings as Record<string, unknown>), graph: { ...prev, ...next } } }).where(and(eq(projects.id, projectId)));
}

/**
 * Make a timeline clip of the user's own footage into a shot (scene "Your footage", version V1 =
 * the original file), so AI edits, comments, compare and versions work on it like on generated
 * shots. Idempotent per asset: the same file reuses its shot.
 */
export async function ensureClipShot(ctx: AppContext, user: SessionLike, projectId: string, input: { assetId: string; label?: string }) {
  const project = await ownedProject(ctx, user, projectId);
  const asset = await getOwnedAsset(ctx, project.userId, input.assetId);
  if (asset.mediaType !== 'video') throw badRequest('Only video clips can become shots');
  const existing = await ctx.db.select().from(shots).where(and(eq(shots.projectId, projectId), eq(shots.currentAssetId, asset.id)));
  for (const s of existing) {
    const [v] = await ctx.db.select().from(shotVersions).where(and(eq(shotVersions.shotId, s.id), eq(shotVersions.assetId, asset.id)));
    if (v) return { shotId: s.id, versionId: v.id, created: false };
  }
  const sceneRows = await ctx.db.select().from(scenes).where(eq(scenes.projectId, projectId));
  let scene = sceneRows.find((s) => s.title === 'Your footage');
  if (!scene) [scene] = await ctx.db.insert(scenes).values({ projectId, index: sceneRows.length, title: 'Your footage', synopsis: 'Clips uploaded to the editor' }).returning();
  const count = (await ctx.db.select({ id: shots.id }).from(shots).where(eq(shots.projectId, projectId))).length;
  const [shot] = await ctx.db
    .insert(shots)
    .values({ projectId, sceneId: scene!.id, index: count, description: (input.label ?? asset.originalName ?? 'Your footage').slice(0, 200), durationSec: Math.max(1, Math.round((asset.durationMs ?? 5000) / 1000)), status: 'ready', currentAssetId: asset.id })
    .returning();
  const v = await recordShotVersion(ctx.db, { projectId, shotId: shot!.id, assetId: asset.id, source: 'upload', label: 'Original', activate: true });
  return { shotId: shot!.id, versionId: v.id, created: true };
}
